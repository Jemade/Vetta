# In-memory SQLite with StaticPool maintains a single shared in-memory database across all connections
test_engine = create_async_engine(
    "sqlite+aiosqlite://",
    connect_args={"check_same_thread": False},
    poolclass=StaticPool,
)

TestSessionLocal = async_sessionmaker(
    bind=test_engine,
    class_=AsyncSession,
    expire_on_commit=False,
    autocommit=False,
    autoflush=False,
)

session_module.async_engine = test_engine
session_module.async_session_factory = TestSessionLocal
main_module.async_engine = test_engine
worker_module.async_session_factory = TestSessionLocal


